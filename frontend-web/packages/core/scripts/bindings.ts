// Regenerates the settlement contract's TypeScript bindings and copies its Wasm into
// packages/core, so the apps build without stellar-implementation checked out.
//
//   pnpm bindings            generate from stellar-implementation's current Wasm
//   pnpm bindings --build    run `make build` there first
//   pnpm bindings --check    fail if wasm/ doesn't match meta.json, or is older than the
//                            implementation's Wasm (when that repo is present)
//
// The implementation repo is $RTGS_IMPL_DIR, or `stellar-implementation/` next to the main
// checkout of this repo (found through git, so it works from a worktree).
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const coreDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const wasmOut = join(coreDir, "wasm/settlement.wasm");
const metaOut = join(coreDir, "wasm/meta.json");
const bindingsOut = join(coreDir, "src/generated/settlement.ts");

interface Meta {
  sha256: string;
  implCommit: string;
  implDirty: boolean;
  stellarCli: string;
  generatedAt: string;
}

function run(cmd: string, args: string[], cwd?: string): string {
  return execFileSync(cmd, args, { cwd, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] }).trim();
}

function sha256(bytes: Uint8Array): string {
  return createHash("sha256").update(bytes).digest("hex");
}

function implDir(): string {
  if (process.env.RTGS_IMPL_DIR) return resolve(process.env.RTGS_IMPL_DIR);
  const commonDir = run("git", ["rev-parse", "--path-format=absolute", "--git-common-dir"], coreDir);
  // <rtgs>/stellar-front/.git -> <rtgs>/stellar-implementation
  return resolve(dirname(commonDir), "../stellar-implementation");
}

function implWasm(dir: string): string {
  return join(dir, "target/wasm32v1-none/release/settlement.wasm");
}

function check(): void {
  const meta = JSON.parse(readFileSync(metaOut, "utf8")) as Meta;
  const committed = sha256(readFileSync(wasmOut));
  if (committed !== meta.sha256) {
    throw new Error(`wasm/settlement.wasm (${committed}) does not match wasm/meta.json (${meta.sha256})`);
  }
  const source = implWasm(implDir());
  if (!existsSync(source)) {
    console.log(`ok: wasm matches meta.json; ${source} not found, so freshness was not checked`);
    return;
  }
  const current = sha256(readFileSync(source));
  if (current !== meta.sha256) {
    throw new Error(`the bindings are stale: ${source} is ${current}, wasm/ is ${meta.sha256}; run pnpm bindings`);
  }
  console.log(`ok: bindings match ${source}`);
}

function generate(build: boolean): void {
  const dir = implDir();
  if (build) execFileSync("make", ["-C", dir, "build"], { stdio: "inherit" });
  const source = implWasm(dir);
  if (!existsSync(source)) throw new Error(`no ${source}; run with --build, or make -C ${dir} build`);

  const tmp = mkdtempSync(join(tmpdir(), "rtgs-bindings-"));
  try {
    // The one place the generator is named (the CLI's TypeScript generator; the brief fixes it).
    execFileSync(
      "stellar",
      ["contract", "bindings", "typescript", "--wasm", source, "--output-dir", join(tmp, "settlement"), "--overwrite"],
      { stdio: ["ignore", "ignore", "inherit"] },
    );
    const generated = readFileSync(join(tmp, "settlement/src/index.ts"), "utf8");
    // The contract's spec can reference types it doesn't define yet (a stub's return type), so
    // the generated file isn't type-checked; src/contract/ owns the domain types.
    const header =
      "// @ts-nocheck\n" +
      "// GENERATED by `pnpm bindings` from stellar-implementation's settlement.wasm. Don't edit.\n";
    writeFileSync(bindingsOut, header + generated);
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }

  const wasm = readFileSync(source);
  writeFileSync(wasmOut, wasm);
  const meta: Meta = {
    sha256: sha256(wasm),
    implCommit: run("git", ["rev-parse", "HEAD"], dir),
    implDirty: run("git", ["status", "--porcelain", "--", "contracts", "crates"], dir) !== "",
    stellarCli: run("stellar", ["--version"]).split("\n")[0] ?? "",
    generatedAt: new Date().toISOString(),
  };
  writeFileSync(metaOut, JSON.stringify(meta, null, 2) + "\n");
  console.log(`generated src/generated/settlement.ts and wasm/ from ${source} (${meta.sha256.slice(0, 12)})`);
}

const args = process.argv.slice(2);
try {
  if (args.includes("--check")) check();
  else generate(args.includes("--build"));
} catch (e) {
  console.error(`bindings: ${(e as Error).message}`);
  process.exit(1);
}
